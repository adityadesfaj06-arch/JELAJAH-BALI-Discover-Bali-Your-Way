export function recommendToursForStops(selectedStopIds: string[]): TourPackage[] {
  if (selectedStopIds.length === 0) return TOUR_PACKAGES;
  return [...TOUR_PACKAGES].sort((a, b) => {
    const overlapA = a.routeStopIds.filter((id) => selectedStopIds.includes(id)).length;
    const overlapB = b.routeStopIds.filter((id) => selectedStopIds.includes(id)).length;
    return overlapB - overlapA;
  });
}

